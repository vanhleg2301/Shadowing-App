-- Video catalog managed from /admin/videos (replaces the hard-coded list in src/data/curated.ts,
-- which stays as a fallback), plus an audit log of admin actions.
-- Run once in Supabase Dashboard -> SQL Editor.

create table if not exists public.videos (
  video_id text primary key check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
  title text not null check (char_length(title) between 1 and 200),
  level text not null check (level in ('A1', 'A2', 'B1')),
  topic text not null check (char_length(topic) between 1 and 60),
  duration text not null default '' check (char_length(duration) <= 10),
  channel text not null default '' check (char_length(channel) <= 100),
  is_published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists videos_published_sort_idx on public.videos (is_published, sort_order);

alter table public.videos enable row level security;

-- Everyone sees published videos; changes go through the service role (admin panel), which bypasses RLS.
create policy "videos_select_published" on public.videos for select to anon, authenticated using (is_published);

-- Who did what in the admin panel. No policies: only the service role can read or write it.
create table if not exists public.admin_audit (
  id bigint generated always as identity primary key,
  admin_email text not null,
  action text not null,
  target text,
  details jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_created_idx on public.admin_audit (created_at desc);

alter table public.admin_audit enable row level security;

